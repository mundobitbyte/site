import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {Script} from 'node:vm';

const pages=[
 'pages/arduino.html',
 'pages/arduino-programacao-aplicada.html',
 'pages/arduino-conectividade.html',
 'pages/arduino-iot.html',
 'pages/arduino-granja-inteligente.html',
 'pages/arduino-protocolos.html',
 'pages/arduino-seguranca.html',
 'pages/arduino-projeto-iot.html',
 'pages/arduino-exercicios.html',
 'pages/arduino-revisao-modulos.html',
 'pages/arduino-avaliacao-conceitual.html',
 'pages/arduino-avaliacoes-bimestrais.html'
];
const overview={pages:[],localLinks:0,anchors:0,assets:0,sourceChecks:0};
const broken=[];
const ignored=[];
const fromRoot=p=>path.resolve(process.cwd(),p);
const extract=(s,rx)=>[...s.matchAll(rx)].map(m=>m[1]);
const ids=new Map();
for(const file of pages) {
  assert(fs.existsSync(file),'Página esperada não existe: '+file);
  const html=fs.readFileSync(file,'utf8');
  const pageIds=new Set(extract(html,/\bid=["']([^"']+)["']/g));
  ids.set(file,pageIds);
  assert(html.includes('<main') && html.includes('</main>'), 'Sem main: '+file);
  const scrips=extract(html,/<script[^>]+src=["']([^"']+)["']/g);
  for(const src of scrips) {
    const srcpath=src.split(/[?#]/)[0];
    if(/^https?:|^\/\//.test(srcpath))continue;
    const target=path.normalize(path.join(path.dirname(file),srcpath));
    overview.sourceChecks++;
    if(!fs.existsSync(target))broken.push(file+' -> SCRIPT inexistente: '+src);
    else { const code=fs.readFileSync(target,'utf8'); try{new Script(code,{filename:target})}catch(e){broken.push(target+': sintaxe '+e.message)} }
  }
  for(const src of extract(html,/<(?:img|link)[^>]+(?:src|href)=["']([^"']+)["']/g)){
    const clean=src.split(/[?#]/)[0];
    if(!clean||/^https?:|^\/\/|^data:|^mailto:/.test(clean))continue;
    if(clean.startsWith('/')){ignored.push(file+' -> '+src);continue}
    const target=path.normalize(path.join(path.dirname(file),clean));
    overview.assets++;
    if(!fs.existsSync(target))broken.push(file+' -> ASSET inexistente: '+src);
  }
  const links=extract(html,/<a\b[^>]*\bhref=["']([^"']+)["']/g);
  for(const href of links){
    if(!href || /^(https?:|mailto:|tel:|javascript:|\/\/)/i.test(href))continue;
    if(href.startsWith('/')){ignored.push(file+' -> '+href);continue}
    const [targetPart,hash]=href.split('#');
    const clean=(targetPart||'').split(/[?]/)[0];
    const target=path.normalize(path.join(path.dirname(file),clean));
    if(!clean && !hash)continue;
    overview.localLinks++;
    if(!fs.existsSync(target)){broken.push(file+' -> LINK inexistente: '+href);continue}
    if(hash && !hash.startsWith(':~:text') && target.endsWith('.html')){
      overview.anchors++;
      const destHtml=fs.readFileSync(target,'utf8');
      if(!new RegExp('\\bid=["\\\']'+hash.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')+'["\\\']').test(destHtml)){
        // Links generated by the navigation script are inspected in the browser tests.
        const targetIds=ids.get(target) || new Set(extract(destHtml,/\bid=["']([^"']+)["']/g));
        if(!targetIds.has(decodeURIComponent(hash).replace(/&amp;/g,'&')))
          broken.push(file+' -> ÂNCORA estática inexistente: '+href);
      }
    }
  }
  overview.pages.push({page:file,ids:pageIds.size,scripts:scrips.length,links:links.length});
}
for(const file of ['pages/arduino.html','pages/arduino-programacao-aplicada.html','pages/arduino-conectividade.html','pages/arduino-iot.html','pages/arduino-protocolos.html','pages/arduino-seguranca.html','pages/arduino-projeto-iot.html']){
  const html=fs.readFileSync(file,'utf8');
  assert(html.includes('mbb-busca-global.js'),'Sem pesquisa global: '+file);
}
for(const [page,tokens] of Object.entries({
  'pages/arduino.html':['id="p1"','id="p2"','id="p3"','id="p4"','id="p5"','id="p6"','id="p7"','id="p8"','id="p9"'],
  'pages/arduino-programacao-aplicada.html':['id="b5-1"','id="b5-2"','id="b5-3"','id="b5-4"'],
  'pages/arduino-conectividade.html':['id="b6-0"','id="b6-prep"','id="b6-1"','id="b6-2"','id="b6-3"','id="b6-4"','id="b6-5"'],
  'pages/arduino-iot.html':['id="b7-1"','id="b7-2"','id="b7-3"','id="b7-4"','id="b7-5"'],
  'pages/arduino-protocolos.html':['id="b8-prep"','id="b8-1"','id="b8-2"','id="b8-3"','id="b8-4"','id="b8-5"','id="b8-6"','id="b8-7"'],
  'pages/arduino-seguranca.html':['id="b9-prep"','id="b9-1"','id="b9-2"'],
  'pages/arduino-projeto-iot.html':['id="b10-1"','id="b10-2"','id="b10-3"','id="b10-4"','id="b10-5"','id="b10-6"','id="b10-7"','id="b10-local"','id="b10-final"','id="b10-wokwi-diagram"']
})){
  const source=fs.readFileSync(page,'utf8');
  for(const token of tokens)assert(source.includes(token),'Marcador essencial ausente: '+page+' '+token);
}
console.log(JSON.stringify({summary:overview,issues:broken,ignoredRootLinks:ignored.slice(0,20)},null,2));
assert.deepEqual(broken,[],'Falhas de navegação, recurso ou sintaxe detectadas no percurso.');
